CREATE TABLE IF NOT EXISTS accounting_accountant_accruals (
  id CHAR(32) PRIMARY KEY,
  owner_id CHAR(32) NOT NULL,
  client_id CHAR(32) NOT NULL,
  invoice_id CHAR(32) NOT NULL,
  payment_id CHAR(32) NOT NULL,
  service_key VARCHAR(128) NOT NULL,
  service_name VARCHAR(190) NOT NULL,
  period_key VARCHAR(20) NOT NULL,
  accountant_id CHAR(32) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending_manager',
  source_payment_amount DECIMAL(14,2) NOT NULL,
  source_invoice_total DECIMAL(14,2) NOT NULL,
  calculation_snapshot JSON NOT NULL,
  requested_at DATETIME NULL,
  requested_by CHAR(32) NULL,
  decided_at DATETIME NULL,
  decided_by CHAR(32) NULL,
  decision_comment VARCHAR(1000) NULL,
  paid_at DATE NULL,
  paid_by CHAR(32) NULL,
  paid_comment VARCHAR(1000) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_accountant_accrual_source (owner_id, payment_id, accountant_id, service_key),
  KEY idx_accountant_accrual_owner_status (owner_id, status, created_at),
  KEY idx_accountant_accrual_accountant (owner_id, accountant_id, status),
  KEY idx_accountant_accrual_client_period (owner_id, client_id, period_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS accounting_accountant_accrual_history (
  id CHAR(32) PRIMARY KEY,
  owner_id CHAR(32) NOT NULL,
  accrual_id CHAR(32) NOT NULL,
  action VARCHAR(32) NOT NULL,
  old_status VARCHAR(24) NULL,
  new_status VARCHAR(24) NULL,
  old_amount DECIMAL(14,2) NULL,
  new_amount DECIMAL(14,2) NULL,
  comment VARCHAR(1000) NULL,
  user_id CHAR(32) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_accountant_accrual_history (owner_id, accrual_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
